#!/usr/bin/env node

/**
 * Interactive Playwright REPL driver for the REAL Electron app, built for
 * verifying DiagnosticsPage's sandboxed-iframe work live (sandbox isolation
 * proofs, CSS/Chart.js checks, the postMessage auth proxy, pagination,
 * height/width jitter measurements). Reusable for any live-UI check.
 *
 * How to use (agent-friendly: pipe commands in, tail the log):
 *
 *   # 1. vite dev server must be running:
 *   npm run dev &
 *
 *   # 2. start the driver behind a command pipe:
 *   cd /tmp && : > cmds.txt && : > driver.log
 *   (tail -f cmds.txt | node <repo>/tests/diagnostics-live-driver.mjs >> driver.log 2>&1 &)
 *
 *   # 3. send commands, read driver.log:
 *   echo launch >> cmds.txt
 *   echo 'ss landing' >> cmds.txt
 *   echo 'evalfile tests/helpers/diagnostics-driver/goto_diag.js' >> cmds.txt
 *
 * Commands: launch, ss [name], windows, usewin <i>, click <sel>,
 *   click-text <text>, type <text>, press <key>, wait <sel>, eval <js>,
 *   evalfile <path>, frames, fevalfile <frameIdx> <path>, token,
 *   text [sel], quit, help.
 *
 * The evalfile/fevalfile payload scripts used for the diagnostics
 * verification rounds live in tests/helpers/diagnostics-driver/ - see the
 * header of each. fevalfile evaluates INSIDE the sandboxed diagnostics
 * iframe (usually frame index 1), which is how the isolation proofs and
 * in-frame pagination checks are done.
 *
 * IMPORTANT - dev-mode backend/token dance: in dev the Electron main spawns
 * electron/server.cjs (Node) on :8080, but the diagnostics endpoints live in
 * the FLASK backend, and every request is gated on a per-launch random
 * X-App-Token generated by the Electron main process. To point the running
 * app at a real Flask backend:
 *
 *   echo token >> cmds.txt          # writes the live token to APP_TOKEN_FILE
 *   pkill -f "electron/server.cjs"  # free :8080 (main.cjs does not respawn it)
 *   cd backend && APP_AUTH_TOKEN=$(cat /tmp/diag-scratch/app-token) PORT=8080 \
 *     venv/bin/python3 app.py &
 *   # NOTE when killing Flask later: ps shows it as ".../MacOS/Python app.py",
 *   # so pkill -f "python3 app.py" will NOT match it. Use:
 *   pkill -f "MacOS/Python app.py"
 *
 * Synthetic report data (no real customer data - see memory note "no real
 * data in fixtures"): tests/helpers/diagnostics-driver/make_fixture.py
 * builds a sosreport-shaped tree under /tmp/diag-reports which the app can
 * load via Diagnostics > Browse different location > /tmp/diag-reports.
 *
 * Deliberately NOT named *.test.mjs: tests/run-all.sh auto-runs that glob,
 * and this opens a GUI window and runs until quit - it is an interactive
 * tool, not a pass/fail test.
 *
 * Dependency: playwright-core (auto-installed --no-save if missing, same
 * convention as smoke-boot-after-dep-update.mjs).
 */

import { execFileSync } from 'node:child_process';
import * as readline from 'node:readline';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SHOT_DIR = process.env.SCREENSHOT_DIR || '/tmp/diag-scratch/shots';
const APP_TOKEN_FILE = process.env.APP_TOKEN_FILE || '/tmp/diag-scratch/app-token';
fs.mkdirSync(SHOT_DIR, { recursive: true });
fs.mkdirSync(path.dirname(APP_TOKEN_FILE), { recursive: true });

if (!fs.existsSync(path.join(APP_DIR, 'node_modules', 'playwright-core'))) {
  console.log('playwright-core missing - installing with --no-save ...');
  execFileSync('npm', ['install', '--no-save', 'playwright-core'], { cwd: APP_DIR, stdio: 'inherit' });
}
const { _electron: electron } = await import('playwright-core');

let app = null;
let page = null;

const electronBin = process.platform === 'darwin'
  ? path.join(APP_DIR, 'node_modules/electron/dist/Electron.app/Contents/MacOS/Electron')
  : path.join(APP_DIR, 'node_modules/electron/dist/electron');

const COMMANDS = {
  async launch() {
    if (app) return console.log('already launched');
    app = await electron.launch({
      executablePath: electronBin,
      args: [APP_DIR],
      env: { ...process.env, PORT: process.env.PORT || '8080' },
      timeout: 45000,
    });
    // Wait for the real UI window (the vite URL), not the devtools window
    // that dev mode auto-opens.
    for (let i = 0; i < 60; i++) {
      page = app.windows().find(w => w.url().startsWith('http://localhost:5173'));
      if (page) break;
      await new Promise(r => setTimeout(r, 500));
    }
    if (!page) page = await app.firstWindow();
    try { await page.waitForLoadState('domcontentloaded', { timeout: 15000 }); } catch { /* keep going */ }
    console.log('launched.', app.windows().length, 'windows:');
    for (const w of app.windows()) console.log(' ', w.url());
  },

  async ss(name) {
    if (!page) return console.log('ERROR: launch first');
    const f = path.join(SHOT_DIR, (name || `ss-${Date.now()}`) + '.png');
    try {
      await page.screenshot({ path: f, timeout: 8000 });
    } catch {
      // page.screenshot's CDP path breaks when devtools is docked; capture
      // via the Electron main process instead - it also captures mid-parse
      // paints because it never touches the renderer's JS thread.
      const b64 = await app.evaluate(async ({ BrowserWindow }) => {
        const w = BrowserWindow.getAllWindows().find(x => !x.webContents.getURL().startsWith('devtools'));
        const img = await w.webContents.capturePage();
        return img.toPNG().toString('base64');
      });
      fs.writeFileSync(f, Buffer.from(b64, 'base64'));
    }
    console.log('screenshot:', f);
  },

  async windows() {
    if (!app) return console.log('ERROR: launch first');
    app.windows().forEach((w, i) => console.log(i, w.url().slice(0, 90)));
  },

  async usewin(i) {
    page = app.windows()[parseInt(i, 10)];
    console.log('page =', page && page.url());
  },

  // DOM click, not locator.click(): coordinate-based clicks can hit the
  // wrong layer; el.click() always reaches the intended element.
  async click(sel) {
    if (!page) return console.log('ERROR: launch first');
    const r = await page.evaluate(s => {
      const el = document.querySelector(s);
      if (!el) return 'NOT_FOUND';
      el.click(); return 'OK';
    }, sel);
    console.log('click', sel, '->', r);
  },

  async 'click-text'(text) {
    if (!page) return console.log('ERROR: launch first');
    const r = await page.evaluate(t => {
      const els = [...document.querySelectorAll('button, a, [role="button"]')];
      const el = els.find(e => e.textContent?.trim() === t)
              ?? els.find(e => e.textContent?.includes(t));
      if (!el) return 'NOT_FOUND';
      el.click(); return 'OK: ' + (el.textContent || '').trim().slice(0, 60);
    }, text);
    console.log('click-text', JSON.stringify(text), '->', r);
  },

  async type(text)  { if (page) await page.keyboard.type(text, { delay: 20 }); console.log('typed'); },
  async press(key)  { if (page) await page.keyboard.press(key); console.log('pressed', key); },

  async wait(sel) {
    if (!page) return console.log('ERROR: launch first');
    try { await page.waitForSelector(sel, { timeout: 15000 }); console.log('found:', sel); }
    catch { console.log('TIMEOUT:', sel); }
  },

  async eval(expr) {
    if (!page) return console.log('ERROR: launch first');
    try { console.log(JSON.stringify(await page.evaluate(expr))); }
    catch (e) { console.log('ERROR:', e.message); }
  },

  // Evaluate a JS file (an IIFE returning a value) in the main page.
  async evalfile(p) {
    if (!page) return console.log('ERROR: launch first');
    const src = fs.readFileSync(path.resolve(APP_DIR, p.trim()), 'utf8');
    try {
      const out = await page.evaluate(src);
      console.log(typeof out === 'string' ? out : JSON.stringify(out, null, 1));
    } catch (e) { console.log('ERROR:', e.message); }
  },

  async frames() {
    if (!page) return console.log('ERROR: launch first');
    page.frames().forEach((f, i) => console.log(i, f.url().slice(0, 80) || '(srcdoc/about)'));
  },

  // Evaluate a JS file inside frame N. The sandboxed diagnostics iframe is
  // normally index 1 (0 is the main page). Works despite the frame's opaque
  // origin - this is how the sandbox-isolation proofs are run.
  async fevalfile(args) {
    if (!page) return console.log('ERROR: launch first');
    const [idxStr, ...rest] = args.trim().split(/\s+/);
    const f = page.frames()[parseInt(idxStr, 10)];
    if (!f) return console.log('ERROR: no frame', idxStr);
    const src = fs.readFileSync(path.resolve(APP_DIR, rest.join(' ')), 'utf8');
    try {
      const out = await f.evaluate(src);
      console.log(typeof out === 'string' ? out : JSON.stringify(out, null, 1));
    } catch (e) { console.log('ERROR:', e.message); }
  },

  // Write the app's per-launch backend auth token to APP_TOKEN_FILE so a
  // manually-started Flask backend can be given the same token.
  async token() {
    if (!page) return console.log('ERROR: launch first');
    const t = await page.evaluate(() => window.electronAPI.getAppToken());
    fs.writeFileSync(APP_TOKEN_FILE, t);
    console.log(`token written to ${APP_TOKEN_FILE} (len ${t.length})`);
  },

  async text(sel) {
    if (!page) return console.log('ERROR: launch first');
    console.log(await page.evaluate(
      s => (s ? document.querySelector(s) : document.body)?.innerText?.slice(0, 3000) ?? '(null)',
      sel || null));
  },

  async quit() { if (app) await app.close().catch(() => {}); app = null; page = null; },
  help() { console.log('commands:', Object.keys(COMMANDS).join(', ')); },
};

// Read the raw stdin fd so Electron cannot steal stdin from the REPL.
const stdin = fs.createReadStream(null, { fd: fs.openSync('/dev/stdin', 'r') });
const rl = readline.createInterface({ input: stdin, output: process.stdout, prompt: 'driver> ' });

rl.on('line', async line => {
  const [cmd, ...rest] = line.trim().split(/\s+/);
  if (!cmd) return rl.prompt();
  const fn = COMMANDS[cmd];
  if (!fn) { console.log('unknown:', cmd, '- try: help'); return rl.prompt(); }
  try { await fn(rest.join(' ')); } catch (e) { console.log('ERROR:', e.message); }
  if (cmd === 'quit') { rl.close(); process.exit(0); }
  rl.prompt();
});
rl.on('close', async () => { await COMMANDS.quit(); process.exit(0); });

console.log('jacarium driver - "help" for commands, "launch" to start');
rl.prompt();
